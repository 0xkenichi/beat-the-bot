// Copies contract ABIs (and the QuoteProbe runtime code) from Foundry's build output into the shared package.
// Run after `forge build`: pnpm tsx scripts/gen-abis.ts
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "contracts/out");
const names = ["PickBook", "PrizePool", "AgentRoster"] as const;
let src = "// Generated by scripts/gen-abis.ts from contracts/out. Do not edit.\n\n";
for (const n of names) {
  const j = JSON.parse(readFileSync(join(out, `${n}.sol/${n}.json`), "utf8"));
  src += `export const ${n[0]!.toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(j.abi, null, 2)} as const;\n\n`;
  src += `export const ${n[0]!.toLowerCase()}${n.slice(1)}Bytecode = ${JSON.stringify(j.bytecode.object)} as const;\n\n`;
}
const probe = JSON.parse(readFileSync(join(out, "QuoteProbe.sol/QuoteProbe.json"), "utf8"));
src += `export const quoteProbeAbi = ${JSON.stringify(probe.abi, null, 2)} as const;\n\n`;
src += `export const quoteProbeRuntime = ${JSON.stringify(probe.deployedBytecode.object)} as const;\n`;
mkdirSync(join(root, "shared/src/generated"), { recursive: true });
writeFileSync(join(root, "shared/src/generated/contracts.ts"), src);
console.log("wrote shared/src/generated/contracts.ts");
