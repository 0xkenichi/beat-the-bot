export type CopyKey = keyof typeof en;

/** Pidgin: Kenichi's copy goes here. Missing keys fall back to English. */
export const pcm: Partial<Record<CopyKey, string>> = {};

export function t(lang: Lang, key: CopyKey, vars: Record<string, string> = {}): string {
  const s = (lang === "pcm" ? pcm[key] : undefined) ?? en[key];
  return s.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? `{${k}}`);
}
